/**
 * ตรวจว่าเครื่องนี้ใช้โค้ดรุ่นล่าสุดหรือยัง
 *
 * ── ทำไมต้องมี ──────────────────────────────────────────────────
 * เครื่องที่ cache ไฟล์เก่าค้างไว้ทำให้แก้บั๊กแล้วผู้ใช้ยังเจอปัญหาเดิม
 * แล้วแจ้งซ้ำเรื่องที่แก้ไปแล้ว โดยไม่มีใครรู้ว่ากำลังคุยกันคนละเวอร์ชัน
 *
 * ── ทำไมแยกไฟล์ ──────────────────────────────────────────────────
 * ตอนแรกเขียนฝังไว้ใน setup() ของ app.js ซึ่งแปลว่าเทสด้วย node ไม่ได้เลย
 * ส่วนที่ผิดแล้วเจ็บที่สุดคือ "ไฟล์ไหนบ้างที่ต้องล้าง cache" — ตกไฟล์เดียว
 * ก็ได้โค้ดใหม่ไม่ครบ แล้วอาการจะเหมือนอัปเดตไม่สำเร็จโดยไม่มีอะไรฟ้อง
 * ตรรกะนั้นจึงต้องอยู่ในที่ที่เทสได้ ไม่ใช่ในที่ที่ต้องเปิดเบราว์เซอร์ถึงจะรู้ว่าถูก
 */

/**
 * ดึงเลขเวอร์ชันออกจากข้อความ HTML ของ index.html
 *
 * meta ตัวนี้อยู่ใน head ก่อนสคริปต์เสมอ จึงไม่มีทางไปจับโค้ดของตัวเอง
 * คืนค่าว่างเมื่อหาไม่เจอ ให้ผู้เรียกตัดสินใจเอง — ที่นี่ไม่ควรโยน error
 * เพราะการตรวจเวอร์ชันล้มเหลวห้ามทำให้แอปใช้งานไม่ได้
 */
export function versionFromHtml(html) {
  const m = String(html || '').match(/<meta\s+name=["']app-version["']\s+content=["']([^"']*)["']/i);
  return m ? m[1] : '';
}

/**
 * เทียบเวอร์ชันที่รันอยู่กับที่อยู่บนเซิร์ฟเวอร์
 *
 * เทียบแบบ "ไม่เท่ากัน" ไม่ใช่ "ใหม่กว่า" โดยตั้งใจ
 * เพราะกรณีที่ต้องเตือนจริง ๆ รวมถึงตอนย้อนเวอร์ชันกลับด้วย (rollback)
 * เครื่องที่ค้างอยู่กับรุ่นที่มีบั๊กต้องถูกดึงกลับมาให้ตรงกับเซิร์ฟเวอร์เสมอ
 */
export const isStale = (running, onServer) =>
  !!onServer && !!running && onServer !== running;

/**
 * ไฟล์ที่ต้องล้าง cache ก่อนโหลดใหม่
 *
 * ── ทำไมไม่เขียนรายชื่อไฟล์ไว้ตายตัว ─────────────────────────────
 * v2 มี ES module สิบกว่าไฟล์ที่เบราว์เซอร์ cache แยกกัน
 * โหลด index.html ใหม่เฉย ๆ ยังหยิบ app.js เก่ามาใช้ได้สบาย
 * ผลคือดูเหมือนอัปเดตแล้วแต่บั๊กยังอยู่ ซึ่งแย่กว่าไม่มีปุ่มอัปเดตเลย
 *
 * รายชื่อที่เขียนไว้เองจะล้าสมัยทันทีที่มีคนเพิ่มโมดูล แล้วไฟล์ที่ตกหล่น
 * จะค้างเป็นของเก่าอยู่เครื่องเดียวโดยไม่มีใครรู้
 * จึงอ่านจากสิ่งที่เบราว์เซอร์โหลดไปจริง (performance resource entries) แทน
 *
 * lib/ ไม่ต้องยุ่ง เป็นไลบรารีตรึงเวอร์ชัน ไม่เคยเปลี่ยนพร้อมโค้ดเรา
 * และไฟล์พวกนั้นใหญ่ที่สุดในโปรเจกต์ ดึงใหม่ทุกครั้งคือทรมานเน็ตโรงงานเปล่า ๆ
 */
export function filesToBust(resourceNames, baseHref, indexName = 'index.html') {
  const base = String(baseHref || '');
  const out = [];
  for (const raw of resourceNames || []) {
    const n = String(raw || '');
    if (!base || !n.startsWith(base)) continue;   // ของนอกโฟลเดอร์แอปไม่ใช่ธุระเรา
    if (n.includes('/lib/')) continue;
    if (!/\.(js|css|html)(\?|#|$)/.test(n)) continue;
    const clean = n.split('#')[0].split('?')[0];  // ตัวเดียวกันที่ต่อ query มาคือไฟล์เดียวกัน
    if (!out.includes(clean)) out.push(clean);
  }
  // index.html ต้องอยู่ในรายการเสมอ แม้เบราว์เซอร์จะไม่ได้นับเป็น resource
  // เพราะมันคือไฟล์ที่บอกเวอร์ชัน ถ้าไม่ล้าง จะเห็นเลขเก่าค้างต่อไปอีกรอบ
  const index = base + indexName;
  if (!out.includes(index)) out.push(index);
  return out;
}
